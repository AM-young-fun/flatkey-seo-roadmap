// Development-only generator; emitted client remains standalone.
const fs = require("node:fs"), path = require("node:path"), crypto = require("node:crypto"), ts = require("typescript");
const root=path.resolve(__dirname,"..");
const source=fs.readFileSync(path.join(root,"src/lib/seo-workflow.ts"),"utf8");
const names=new Set(["WORKFLOW_SITES", "WORKFLOW_MARKETS", "WORKFLOW_SITE_LANGUAGES", "workflowContentLanguages", "WORKFLOW_STATUSES", "workflowRecordIdSchema", "id", "stamp", "workflowWeekSchema", "site", "country", "language", "httpsUrl", "workflowEvidenceSchema", "evidence", "taskProgress", "approval", "research", "workflowCodeSourceSchema", "workflowTaskSchema", "workflowIssueSchema", "githubReviewBelongsToSite", "pageBelongsToSite", "productReviewBelongsToSite", "shiftWorkflowDay"]);
function selected(source,names){const ast=ts.createSourceFile("contract.ts",source,ts.ScriptTarget.Latest,true);return ast.statements.filter(node=>ts.isVariableStatement(node)?node.declarationList.declarations.some(row=>names.has(row.name.getText(ast))):ts.isFunctionDeclaration(node)&&names.has(node.name?.text)).map(node=>node.getText(ast));}
function selectedDependencies(source,roots){
  const ast=ts.createSourceFile("dependencies.ts",source,ts.ScriptTarget.Latest,true), declarations=new Map(), imported=new Map();
  for(const node of ast.statements){
    if(ts.isImportDeclaration(node)&&node.importClause&&!node.importClause.isTypeOnly){
      const clause=node.importClause;
      if(clause.name)imported.set(clause.name.text,node.moduleSpecifier.text);
      if(clause.namedBindings&&ts.isNamedImports(clause.namedBindings))for(const item of clause.namedBindings.elements)if(!item.isTypeOnly)imported.set(item.name.text,node.moduleSpecifier.text);
      if(clause.namedBindings&&ts.isNamespaceImport(clause.namedBindings))imported.set(clause.namedBindings.name.text,node.moduleSpecifier.text);
    }
    const names=ts.isVariableStatement(node)?node.declarationList.declarations.map(row=>row.name.getText(ast)):ts.isFunctionDeclaration(node)&&node.name?[node.name.text]:[];
    for(const name of names)declarations.set(name,node);
  }
  const selectedNodes=new Set(), visit=name=>{
    const node=declarations.get(name);
    if(!node){if(roots.has(name))throw Error("schema_dependency_root_missing:"+name);return;}
    if(selectedNodes.has(node))return;
    selectedNodes.add(node);
    const references=child=>{
      if(ts.isIdentifier(child)){
        if(imported.has(child.text)&&(child.text!=="z"||imported.get(child.text)!=="zod"))throw Error("standalone_schema_external_dependency:"+child.text);
        if(declarations.has(child.text))visit(child.text);
      }
      ts.forEachChild(child,references);
    };
    ts.forEachChild(node,references);
  };
  for(const root of roots)visit(root);
  return ast.statements.filter(node=>selectedNodes.has(node)).map(node=>node.getText(ast));
}
const chunks=selected(source,names);
const marketSource=fs.readFileSync(path.join(root,"src/lib/seo-growth-markets.ts"),"utf8");
const markets=selected(marketSource,new Set(["GROWTH_MARKET_LANGUAGES","GROWTH_LANGUAGES","GROWTH_COUNTRIES"]));
const maintenanceSource=fs.readFileSync(path.join(root,"src/lib/seo-maintenance.ts"),"utf8");
const maintenance=selectedDependencies(maintenanceSource,new Set(["maintenanceWorkClassSchema","maintenancePlanSchema"]));
// The maintenance module has its own stamp/text/url validators. Keep their
// original scope instead of colliding with the task contract's shared names.
const maintenanceBlock='const { maintenanceWorkClassSchema, maintenancePlanSchema } = (() => {\n'+maintenance.join('\n')+'\nreturn { maintenanceWorkClassSchema, maintenancePlanSchema };\n})();';
const combined=[...markets,maintenanceBlock,...chunks].join("\n");
const hash=crypto.createHash("sha256").update(combined).digest("hex");
const generated=ts.transpileModule('const { z } = require("zod");\n'+combined.replace(/^export /gm,""),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText.replace(/^"use strict";\n/u,"").trim();
const file=path.join(root,"scripts/lib/seo-content-review-schema.cjs");
const old=fs.readFileSync(file,"utf8");
const briefStart=old.indexOf("// BEGIN TASK BRIEF CLIENT CONTRACT"), exportStart=old.indexOf("module.exports =",briefStart);
if(briefStart<0||exportStart<0)throw Error("standalone_brief_contract_missing");
const suffix=old.slice(briefStart,exportStart).trimEnd();
const exportsLine="module.exports = { CLIENT_CONTRACT_VERSION, SOURCE_CONTRACT_SHA256, SOURCE_BRIEF_SHA256, GROWTH_COUNTRIES, GROWTH_LANGUAGES, GROWTH_MARKET_LANGUAGES, WORKFLOW_SITE_LANGUAGES, workflowTaskSchema, workflowIssueSchema, workflowWeekSchema, taskNeedsChineseBrief, workflowTaskBriefProblems };";
const prefix='// Versioned standalone client snapshot; server remains final validator.\n// Generated by scripts/generate-seo-content-review-schema.cjs.\n"use strict";\nconst CLIENT_CONTRACT_VERSION = "seo-content-review-growth-v15";\nconst SOURCE_CONTRACT_SHA256 = "'+hash+'";\n';
fs.writeFileSync(file,prefix+generated+'\n'+suffix+'\n\n'+exportsLine+'\n');
console.log("Generated growth-v1.5 standalone client contract",hash);
